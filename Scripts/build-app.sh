#!/bin/bash
# Build Mackit.app (containing the Contents/Library/LoginItems/MackitAgent.app tray agent)
# Usage: Scripts/build-app.sh [debug|release]
#
# The two bundles ship the same binary, with roles separated by bundle ID:
#   Mackit.app (cn.mingcui.mackit, regular)      main window + scan/clean + Sparkle
#   MackitAgent.app (cn.mingcui.mackit.agent, LSUIElement)  lives in the menu bar
# The processes cooperate via distributed notifications and a shared settings
# file; see Sources/Mackit/IPC/AppBridge.swift for details.
#
# Environment variables:
#   MACKIT_SIGN_IDENTITY  Signing identity. When set, signs with Developer ID
#                         and enables the hardened runtime (a prerequisite for
#                         notarization); when unset, uses a local ad-hoc signature.
#   MACKIT_ARCHES         Space-separated list of architectures, e.g. "arm64
#                         x86_64" builds a universal binary — one package
#                         supports both Apple silicon and Intel.
#                         When unset, builds the machine's native architecture
#                         (the default for development iteration, fastest).
#                         SwiftPM produces the fat file directly for universal
#                         binaries, with artifacts and dSYM paths the same as
#                         single-architecture; x86_64 shows a deprecation
#                         warning in the macOS 27 SDK, but compilation is
#                         unaffected.
#   MACKIT_VERSION        Override the version number (defaults to the most
#                         recent git tag)
#   MACKIT_BUILD_NUMBER   Override the build number (defaults to the commit
#                         count; Sparkle relies on CFBundleVersion to determine
#                         what's new, so it must increase monotonically)
#   MACKIT_UPDATE_FEED_URL   Sparkle appcast URL (https). When set, the main
#                            app's Info.plist gets SUFeedURL and related keys
#                            written, and Sparkle starts with the app; when
#                            unset, development builds have no update source and
#                            update-related UI is hidden.
#   MACKIT_UPDATE_PUBLIC_KEY EdDSA public key (SUPublicEDKey), generated by
#                            Sparkle's generate_keys; used together with the feed.
#   MACKIT_UPDATE_AUTO_CHECK Default for the automatic check switch, default 1
#                            (true).
#   MACKIT_UPDATE_AUTO_UPDATE Default for the automatic download switch, default
#                             0 (false): a found update is offered in the
#                             standard alert, which asks before downloading.
#                             Turning it on (here or in the app's Settings)
#                             makes Sparkle download silently in the background
#                             and install on quit without ever asking — since
#                             Sparkle 2.4 that mode shows no prompt at all, so
#                             the user is never told a new version exists. The
#                             hands-off choice stays available, but it is opt-in.
#   MACKIT_UPDATE_INTERVAL   Scheduled check interval (seconds), default 86400.
set -euo pipefail

CONFIG="${1:-release}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP="$ROOT/Mackit.app"
BUILD_DIR="$ROOT/.build"
BUNDLE_ID="cn.mingcui.mackit"
AGENT_BUNDLE_ID="cn.mingcui.mackit.agent"

cd "$ROOT"

# The macOS deployment target, which must stay in sync with Package.swift's
# `platforms` entry: it is written into both bundles' Info.plist as
# LSMinimumSystemVersion and into the binary's LC_BUILD_VERSION below.
MACOS_MINOS="14.0"
MACOS_SDK_VERSION="$(xcrun --show-sdk-version)"

# SwiftPM stamps the linked binary's LC_BUILD_VERSION with the deployment
# target for BOTH minos and sdk — the driver hands the linker
# `-platform_version macos 14.0 14.0` — so a binary compiled against the
# macOS 27 SDK ends up declaring sdk 14.0. AppKit reads that field to pick
# which generation of window chrome to draw: sdk 14.0 gets the
# pre-macOS-26 traffic lights (12pt discs, glyphs visible at rest) and the
# pre-macOS-26 control metrics, while sdk 26 or later gets the macOS 26+
# Liquid Glass chrome (14pt discs, glyphs on hover) and the new metrics —
# the look every other current app on the system has. Restating the SDK this
# build actually compiled against makes the app render as the macOS 26+ app
# it is, while minos stays at the deployment target so it still installs on
# macOS 14.
LINKER_BUILD_VERSION=(
    -Xlinker -platform_version
    -Xlinker macos
    -Xlinker "$MACOS_MINOS"
    -Xlinker "$MACOS_SDK_VERSION"
)

if [ -n "${MACKIT_ARCHES:-}" ]; then
    echo "==> Building (${CONFIG}, architectures: ${MACKIT_ARCHES})"
    BUILD_ARGS=()
    for arch in $MACKIT_ARCHES; do
        BUILD_ARGS+=(--arch "$arch")
    done
    swift build -c "$CONFIG" "${BUILD_ARGS[@]}" "${LINKER_BUILD_VERSION[@]}"
else
    echo "==> Building (${CONFIG})"
    swift build -c "$CONFIG" "${LINKER_BUILD_VERSION[@]}"
fi

BINARY="$BUILD_DIR/$CONFIG/Mackit"
if [ ! -f "$BINARY" ]; then
    echo "Cannot find $BINARY" >&2
    exit 1
fi

echo "==> Generating app icon"
ICONSET="$BUILD_DIR/AppIcon.iconset"
ICNS="$BUILD_DIR/AppIcon.icns"
# When MACKIT_SKIP_ICON=1, reuse the existing icns to speed up repeated builds.
# Note: do not skip when make-icon.swift has been changed, or the old icon
# will be used.
if [ "${MACKIT_SKIP_ICON:-0}" = "1" ] && [ -f "$ICNS" ]; then
    echo "(reusing existing ${ICNS})"
else
    rm -rf "$ICONSET"
    swift "$ROOT/Scripts/make-icon.swift" "$ICONSET"
    iconutil -c icns "$ICONSET" -o "$ICNS"
fi

# Localization resource bundle: all the *.lproj compiled from the String
# Catalog are inside.
# It must be placed in Contents/Resources for Bundle.module to resolve it.
# Both bundles need a copy: the main window and the tray panel both look up
# the same strings.
# Without it the whole UI would display keys, so a missing resource bundle
# fails the build directly.
RESOURCE_BUNDLE="$BUILD_DIR/$CONFIG/Mackit_Mackit.bundle"
if [ ! -d "$RESOURCE_BUNDLE" ]; then
    echo "Cannot find localization resource bundle $RESOURCE_BUNDLE" >&2
    echo "All UI strings would degrade to keys; aborting the build." >&2
    exit 1
fi

# Sparkle framework: SPM unpacks the XCFramework under .build/artifacts; copy
# it into Contents/Frameworks. The executable built by SPM only carries an
# rpath pointing at .build, so a hand-assembled .app cannot resolve
# @rpath/Sparkle.framework and must be given @executable_path/../Frameworks
# — install_name_tool rewrites the binary, so this must be done before signing.
#
# The agent bundle needs a copy too: the two bundles share the same binary and
# link Sparkle, so the agent cannot even start without the framework (the
# agent never launches the updater, but its symbols must resolve).
echo "==> Embedding Sparkle.framework"
# Prefer the universal slice (macos-arm64_x86_64); in case the upstream switches
# to per-architecture releases, fall back to the first slice so the build is
# not interrupted.
SPARKLE_FRAMEWORK="$(find "$BUILD_DIR/artifacts" -type d -name "Sparkle.framework" -path "*macos-arm64_x86_64*" 2>/dev/null | head -1)"
if [ -z "$SPARKLE_FRAMEWORK" ]; then
    SPARKLE_FRAMEWORK="$(find "$BUILD_DIR/artifacts" -type d -name "Sparkle.framework" 2>/dev/null | head -1)"
fi
if [ -z "$SPARKLE_FRAMEWORK" ] || [ ! -d "$SPARKLE_FRAMEWORK" ]; then
    echo "Cannot find Sparkle.framework ($BUILD_DIR/artifacts)." >&2
    echo "Run swift build once to resolve the Sparkle dependency, then retry." >&2
    exit 1
fi

# Version number: environment variable first, then the most recent git tag,
# and finally falling back to 1.0.
# Manually bumping the version for every release is easy to forget, so the
# git tag is the single source of truth.
if [ -n "${MACKIT_VERSION:-}" ]; then
    VERSION="$MACKIT_VERSION"
elif TAG="$(git -C "$ROOT" describe --tags --abbrev=0 2>/dev/null)"; then
    VERSION="${TAG#v}"
else
    VERSION="1.0"
fi
# The build number defaults to the commit count: Sparkle uses CFBundleVersion
# to tell updates apart, and hard-coding 1 would make the updater always think
# "what's installed is the latest" and never detect new versions.
# The commit count increases monotonically with the repository, satisfying this
# naturally; override it with an environment variable for CI and similar cases.
if [ -n "${MACKIT_BUILD_NUMBER:-}" ]; then
    BUILD_NUMBER="$MACKIT_BUILD_NUMBER"
else
    BUILD_NUMBER="$(git -C "$ROOT" rev-list --count HEAD 2>/dev/null || echo 1)"
fi

# Sparkle update keys: only written when MACKIT_UPDATE_FEED_URL is set. Without
# a feed Sparkle does not launch, and writing a bunch of keys would only put
# unusable switches in the settings page.
if [ -n "${MACKIT_UPDATE_FEED_URL:-}" ] && [ -z "${MACKIT_UPDATE_PUBLIC_KEY:-}" ]; then
    echo "Warning: MACKIT_UPDATE_FEED_URL is set but MACKIT_UPDATE_PUBLIC_KEY is not," >&2
    echo "         Sparkle rejects all updates without an EdDSA public key." >&2
fi

# Convert switch values to plist boolean literals: use case instead of command
# substitution, to avoid splicing environment variables into a command for
# execution (Mimosa warns about the pattern of splicing env vars into $( )).
case "${MACKIT_UPDATE_AUTO_CHECK:-1}" in
    1) AUTO_CHECK_PLIST="<true/>" ;;
    *) AUTO_CHECK_PLIST="<false/>" ;;
esac
case "${MACKIT_UPDATE_AUTO_UPDATE:-0}" in
    1) AUTO_UPDATE_PLIST="<true/>" ;;
    *) AUTO_UPDATE_PLIST="<false/>" ;;
esac
UPDATE_PLIST_KEYS=""
if [ -n "${MACKIT_UPDATE_FEED_URL:-}" ]; then
    UPDATE_PLIST_KEYS="
    <key>SUFeedURL</key>
    <string>${MACKIT_UPDATE_FEED_URL}</string>
    <key>SUPublicEDKey</key>
    <string>${MACKIT_UPDATE_PUBLIC_KEY:-}</string>
    <key>SUEnableAutomaticChecks</key>
    ${AUTO_CHECK_PLIST}
    <key>SUAutomaticallyUpdate</key>
    ${AUTO_UPDATE_PLIST}
    <key>SUScheduledCheckInterval</key>
    <integer>${MACKIT_UPDATE_INTERVAL:-86400}</integer>"
    echo "Update feed: ${MACKIT_UPDATE_FEED_URL}"
fi

echo "==> Assembling Mackit.app and embedded MackitAgent.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# ---- Tray agent (embedded in the main app under Contents/Library/LoginItems) ----
# SMAppService.loginItem only accepts this location. The agent lives in the
# menu bar and does not appear in the Dock, so it needs no icon; no Sparkle
# keys are written at all (updates only happen on the main app side).
AGENT="$APP/Contents/Library/LoginItems/MackitAgent.app"
mkdir -p "$AGENT/Contents/MacOS" "$AGENT/Contents/Resources" "$AGENT/Contents/Frameworks"
cp "$BINARY" "$AGENT/Contents/MacOS/MackitAgent"
cp -R "$RESOURCE_BUNDLE" "$AGENT/Contents/Resources/"
cp -R "$SPARKLE_FRAMEWORK" "$AGENT/Contents/Frameworks/"
install_name_tool -add_rpath @executable_path/../Frameworks "$AGENT/Contents/MacOS/MackitAgent"

cat > "$AGENT/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>zh-Hans</string>
    <key>CFBundleDisplayName</key>
    <string>Mackit Agent</string>
    <key>CFBundleExecutable</key>
    <string>MackitAgent</string>
    <key>CFBundleIdentifier</key>
    <string>$AGENT_BUNDLE_ID</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleLocalizations</key>
    <array>
        <string>zh-Hans</string>
        <string>en</string>
        <string>zh-Hant</string>
        <string>ko</string>
        <string>ja</string>
    </array>
    <key>CFBundleName</key>
    <string>Mackit Agent</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>$VERSION</string>
    <key>CFBundleVersion</key>
    <string>$BUILD_NUMBER</string>
    <key>CFBundleSupportedPlatforms</key>
    <array>
        <string>MacOSX</string>
    </array>
    <key>LSMinimumSystemVersion</key>
    <string>${MACOS_MINOS}</string>
    <!-- LSUIElement: the agent is an accessory — only a menu bar icon, no Dock
         icon, no main window, and absent from the Cmd-Tab list. This is the
         foundation of "the Dock icon disappears after closing the window while
         the tray keeps monitoring": the icon belongs to the agent, the window
         belongs to the main app, each process has a fixed form, and no
         activation policy switching happens at runtime. -->
    <key>LSUIElement</key>
    <true/>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.utilities</string>
    <!-- Disable automatic termination and sudden termination: the agent lives
         in the menu bar with no windows, making it the prime target of the
         system's "looks idle" heuristic (observed in runtime logs as
         _kLSApplicationWouldBeTerminatedByTALKey=1). The polling task keeps
         the process from ever being truly idle, but disabling them explicitly
         is the only reliable way; both keys default to true. -->
    <key>NSSupportsAutomaticTermination</key>
    <false/>
    <key>NSSupportsSuddenTermination</key>
    <false/>
    <key>NSHumanReadableCopyright</key>
    <string>Copyright © 2026 mingcui. All rights reserved.</string>
    <key>NSPrincipalClass</key>
    <string>NSApplication</string>
</dict>
</plist>
PLIST
plutil -lint "$AGENT/Contents/Info.plist" > /dev/null

# ---- Main app ----
cp "$BINARY" "$APP/Contents/MacOS/Mackit"
cp "$BUILD_DIR/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
cp -R "$RESOURCE_BUNDLE" "$APP/Contents/Resources/"
mkdir -p "$APP/Contents/Frameworks"
cp -R "$SPARKLE_FRAMEWORK" "$APP/Contents/Frameworks/"
install_name_tool -add_rpath @executable_path/../Frameworks "$APP/Contents/MacOS/Mackit"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>zh-Hans</string>
    <key>CFBundleDisplayName</key>
    <string>Mackit</string>
    <key>CFBundleExecutable</key>
    <string>Mackit</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>CFBundleIconName</key>
    <string>AppIcon</string>
    <key>CFBundleIdentifier</key>
    <string>$BUNDLE_ID</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleLocalizations</key>
    <array>
        <string>zh-Hans</string>
        <string>en</string>
        <string>zh-Hant</string>
        <string>ko</string>
        <string>ja</string>
    </array>
    <key>CFBundleName</key>
    <string>Mackit</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>$VERSION</string>
    <key>CFBundleVersion</key>
    <string>$BUILD_NUMBER</string>
    <key>CFBundleSupportedPlatforms</key>
    <array>
        <string>MacOSX</string>
    </array>
    <key>LSMinimumSystemVersion</key>
    <string>${MACOS_MINOS}</string>
    <!-- The minimum is aligned with Package.swift's .v14 (compile target
         minos 14.0): there are no APIs above 14.0 in the source, the compiler
         gates them by the 14.0 availability annotations, and swift build emits
         zero availability warnings. The app does not embed the Swift runtime
         (linking the system /usr/lib/swift/* directly), and the linker has no
         version gating for Swift runtime symbols — the SDK's libswift tbd does
         not export per-version. But the compiler picks symbols by the
         deployment target: withTaskGroup(of:returning:isolation:body:), the
         only one needing the macOS 15.0+ runtime, is a weak import whose call
         sites carry a runtime version check, so on 14.x it takes the local
         fallback implementation compiled into the binary.
         When raising platforms in the future, this must be updated in sync —
         MACOS_MINOS above is the single place this script reads it from. -->
    <!-- The main app deliberately stays regular with no LSUIElement: the menu
         bar belongs to the agent, and the Dock icon follows the main process —
         it exists only while the window is open; closing the window quits and
         the icon disappears. -->
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.utilities</string>
    <!-- "Open in Terminal" sends Apple Events to Terminal, and "Show in
         Finder" sends one to Finder to select the revealed file; both the TCC
         authorization prompt and later review require this usage description. -->
    <key>NSAppleEventsUsageDescription</key>
    <string>Mackit needs to control Terminal and Finder to open a terminal window or reveal a file at the selected path.</string>
    <key>NSHumanReadableCopyright</key>
    <string>Copyright © 2026 mingcui. All rights reserved.</string>
    <key>NSPrincipalClass</key>
    <string>NSApplication</string>${UPDATE_PLIST_KEYS}
    <!-- Disable automatic termination and sudden termination: the main app
         quits when its window closes, but between closing the window and
         quitting, and when the user opens the main app directly from Finder,
         the system must not terminate it just because it "has no window and
         looks idle"; it especially must not be killed suddenly while a clean is
         in progress. Both keys default to true and must be disabled explicitly. -->
    <key>NSSupportsAutomaticTermination</key>
    <false/>
    <key>NSSupportsSuddenTermination</key>
    <false/>
</dict>
</plist>
PLIST

# Validate the plist
plutil -lint "$APP/Contents/Info.plist" > /dev/null

# Signing. Defaults to ad-hoc (for running on this machine); when an identity
# is set, signs with Developer ID and enables the hardened runtime. Sign the
# nested resource bundle first, then the outer bundle, and do not use --deep:
# --deep makes codesign recursively rewrite the signatures of nested code,
# which Apple explicitly does not recommend.
#
# Nested hierarchy (inside out):
#   Sparkle's XPCServices/*.xpc, Updater.app and Autoupdate
#   → Sparkle.framework
#   → agent's resource bundle → agent app (it lives inside the main app and
#     must be signed before the main app)
#   → main app's resource bundle → main app
echo "==> Signing"
SIGN_ARGS=(--force --sign)
# Sparkle.framework embeds Updater.app and the two XPC services under
# XPCServices, and the framework ships with its own ad-hoc signature. Every
# layer must be re-signed from the inside out: codesign will not re-sign
# already-signed nested code for you, and leaving the distributor's ad-hoc
# signature would fail notarization (the Team ID would not match).
# Versions/Current is a symlink to the actual version directory; resolve it to
# the real path first.
#
# Autoupdate must be signed separately: the framework's CFBundleExecutable is
# Sparkle, so signing the bundle only re-signs it; Autoupdate is another
# standalone Mach-O in the framework (the helper binary that Updater.app
# actually calls), not the bundle's main executable, so signing the bundle
# never touches it and it would keep the ad-hoc signature shipped with Sparkle
# — notarization requires every Mach-O in the package to have a Developer ID
# signature, and missing it makes notarytool reject the package as Invalid.
sign_nested_sparkle() {
    local framework="$1"
    local real nested
    real="$(cd "$framework/Versions/Current" && pwd -P)"
    for nested in "$real"/XPCServices/*.xpc "$real"/Updater.app "$real"/Autoupdate; do
        [ -e "$nested" ] && codesign "${SIGN_ARGS[@]}" "$IDENTITY" --options runtime --timestamp "$nested"
    done
    codesign "${SIGN_ARGS[@]}" "$IDENTITY" --options runtime --timestamp "$framework"
}
sign_nested_sparkle_adhoc() {
    local framework="$1"
    local real nested
    real="$(cd "$framework/Versions/Current" && pwd -P)"
    for nested in "$real"/XPCServices/*.xpc "$real"/Updater.app "$real"/Autoupdate; do
        [ -e "$nested" ] && codesign "${SIGN_ARGS[@]}" - "$nested"
    done
    codesign "${SIGN_ARGS[@]}" - "$framework"
}

if [ -n "${MACKIT_SIGN_IDENTITY:-}" ]; then
    echo "(Developer ID: ${MACKIT_SIGN_IDENTITY}, hardened runtime enabled)"
    IDENTITY="$MACKIT_SIGN_IDENTITY"
    # agent: resource bundle → Sparkle nesting → framework → agent itself
    codesign "${SIGN_ARGS[@]}" "$IDENTITY" --options runtime --timestamp \
        "$AGENT/Contents/Resources/Mackit_Mackit.bundle"
    sign_nested_sparkle "$AGENT/Contents/Frameworks/Sparkle.framework"
    codesign "${SIGN_ARGS[@]}" "$IDENTITY" --options runtime --timestamp "$AGENT"
    # main app: resource bundle → Sparkle nesting → framework → app itself
    codesign "${SIGN_ARGS[@]}" "$IDENTITY" --options runtime --timestamp \
        "$APP/Contents/Resources/Mackit_Mackit.bundle"
    sign_nested_sparkle "$APP/Contents/Frameworks/Sparkle.framework"
    codesign "${SIGN_ARGS[@]}" "$IDENTITY" --options runtime --timestamp "$APP"
else
    echo "(ad-hoc local signature; set MACKIT_SIGN_IDENTITY for distribution)"
    IDENTITY="-"
    # agent
    codesign "${SIGN_ARGS[@]}" - "$AGENT/Contents/Resources/Mackit_Mackit.bundle"
    # Re-sign the nested XPC and Updater.app with ad-hoc as well, so the whole
    # package is signed the same way and the behavior does not diverge from the
    # distributed build when running Sparkle's XPC validation during development.
    sign_nested_sparkle_adhoc "$AGENT/Contents/Frameworks/Sparkle.framework"
    codesign "${SIGN_ARGS[@]}" - "$AGENT"
    # main app
    codesign "${SIGN_ARGS[@]}" - "$APP/Contents/Resources/Mackit_Mackit.bundle"
    sign_nested_sparkle_adhoc "$APP/Contents/Frameworks/Sparkle.framework"
    codesign "${SIGN_ARGS[@]}" - "$APP"
fi

# Put the dSYM next to the .app: the release build's symbol table does not go
# into the bundle, but without it users' crash reports cannot be symbolicated.
# The two bundles share the same binary, so they share this one dSYM.
DSYM="$BUILD_DIR/$CONFIG/Mackit.dSYM"
if [ -d "$DSYM" ]; then
    rm -rf "$APP.dSYM"
    cp -R "$DSYM" "$APP.dSYM"
    echo "==> dSYM copied to $APP.dSYM (shared by the agent)"
fi

echo
# The braces cannot be omitted: bash 3.2 swallows the non-ASCII bytes following $VAR into the variable name
echo "Done: ${APP} (version ${VERSION}, build ${BUILD_NUMBER})"
echo "Run: open \"${APP}\""
