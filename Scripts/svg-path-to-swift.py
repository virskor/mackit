#!/usr/bin/env python3
"""Convert the sparkle SVG's star paths into a menu bar icon.

Reads Assets/sparkle/sparkle-blue.svg, takes the two star outlines
(back star + front star), and emits:

  1. Sources/Mackit/Views/Components/MenuBarIcon.swift
     — the menu bar icon: paths drawn into a template NSImage, presented
     via Image(nsImage:).
  2. /tmp/menubar-mono.svg — a pure black silhouette of the same paths,
     for render verification.

Implementation notes (all learned the hard way through testing — read before
changing):

  * You cannot use .fill(.primary) directly in SwiftUI: on macOS 27, a
    Shape + fill view inside a MenuBarExtra label does not render at all
    (SF Symbols, text and template NSImages all work — only Shape does not).
    So draw the paths into an isTemplate NSImage and use the same
    template-image channel as SF Symbols, letting the system color it black
    or white automatically according to the menu bar's light/dark appearance.
  * The two stars must be filled separately and not merged into one CGPath:
    in the SVG they are two independent path elements, each filled with
    nonzero; when merged into one path the two subpaths wind in opposite
    directions, the winding numbers cancel to 0 where they overlap, and a
    cross-shaped hole would be punched in the middle of the front star.

Only the commands used by this icon are supported: M L C H V Z (absolute
coordinates). Any other command raises an error directly, to avoid silently
producing an incorrect path.

Usage: python3 Scripts/svg-path-to-swift.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path("/Users/weizhang/Projects/Mackit")
SVG = ROOT / "Assets/sparkle/sparkle-blue.svg"
SWIFT_OUT = ROOT / "Sources/Mackit/Views/Components/MenuBarIcon.swift"
MONO_OUT = pathlib.Path("/tmp/menubar-mono.svg")

NUMBER = re.compile(r"[MmLlHhVvCcZz]|[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")


def tokenize(d: str):
    """-> [(command, [numbers...]), ...]; handles implicit repetition (command letters omitted)."""
    tokens = [m.group(0) for m in NUMBER.finditer(d)]
    out = []
    i = 0
    current = None
    while i < len(tokens):
        tok = tokens[i]
        if re.fullmatch(r"[MmLlHhVvCcZz]", tok):
            current = tok
            i += 1
            if current in "Zz":
                out.append((current, []))
                current = None
                continue
        if current is None:
            raise ValueError("path 以数字开头，缺少 M 命令")
        want = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6}[current.upper()]
        nums = []
        while i < len(tokens) and len(nums) < want and not re.fullmatch(r"[MmLlHhVvCcZz]", tokens[i]):
            nums.append(tokens[i])
            i += 1
        if len(nums) != want:
            raise ValueError(f"命令 {current} 参数不足：{nums}")
        out.append((current, nums))
        # After M, implicit commands are treated as L
        if current.upper() == "M":
            current = "L" if current == "M" else "l"
    return out


def to_swift(commands):
    """Generate the Swift statements for CGMutablePath; H/V fill in the other coordinate from the current point."""
    lines = []
    cx = cy = 0.0
    for cmd, nums in commands:
        if cmd == "M":
            cx, cy = float(nums[0]), float(nums[1])
            lines.append(f"path.move(to: CGPoint(x: {nums[0]}, y: {nums[1]}))")
        elif cmd == "L":
            cx, cy = float(nums[0]), float(nums[1])
            lines.append(f"path.addLine(to: CGPoint(x: {nums[0]}, y: {nums[1]}))")
        elif cmd == "H":
            cx = float(nums[0])
            lines.append(f"path.addLine(to: CGPoint(x: {nums[0]}, y: {cy:g}))")
        elif cmd == "V":
            cy = float(nums[0])
            lines.append(f"path.addLine(to: CGPoint(x: {cx:g}, y: {nums[0]}))")
        elif cmd == "C":
            x1, y1, x2, y2, x, y = (float(n) for n in nums)
            cx, cy = x, y
            lines.append(
                "path.addCurve(to: CGPoint(x: %s, y: %s), "
                "control1: CGPoint(x: %s, y: %s), control2: CGPoint(x: %s, y: %s))"
                % (nums[4], nums[5], nums[0], nums[1], nums[2], nums[3])
            )
        elif cmd == "Z":
            lines.append("path.closeSubpath()")
        else:
            raise ValueError(f"不支持的命令 {cmd}")
    return lines


SWIFT_TEMPLATE = '''import AppKit
import CoreGraphics
import SwiftUI

/// Menu bar tray icon: a two-star monochrome silhouette, with geometry taken
/// from the two star paths (24×24 viewBox) in Assets/sparkle/sparkle-blue.svg,
/// generated by Scripts/svg-path-to-swift.py — do not edit by hand; to change
/// the icon, edit the SVG and regenerate.
///
/// Why detour through NSImage: measured on macOS 27, a Shape + .fill view
/// inside a MenuBarExtra label does not render at all (SF Symbols, text and
/// template NSImages all work — only Shape does not), so the paths are drawn
/// into an isTemplate NSImage and handed to Image(nsImage:) — the same
/// template-image channel as SF Symbols, letting the system color it black or
/// white automatically according to the menu bar's light/dark appearance, with
/// no need to prepare separate day/night assets.
/// Vector paths are rasterized on a 2x pixel grid, so they stay sharp on Retina.
struct MenuBarIcon: View {{
    /// The point size in the menu bar. The menu bar is 24pt high; 16~18 works well when paired with text.
    var pointSize: CGFloat = 17

    var body: some View {{
        Image(nsImage: Self.templateImage(pointSize: pointSize))
    }}

    /// Two-star paths -> template image: a black silhouette + alpha channel;
    /// once isTemplate is set, the system takes only alpha and colors it
    /// according to the menu bar's light/dark appearance. Drawn at 2x pixels;
    /// rebuilt on every body evaluation (a few dozen microseconds, and the
    /// label only redraws when the value changes, so a cache and a concurrency
    /// exemption are not worth introducing for it).
    private static func templateImage(pointSize: CGFloat) -> NSImage {{
        let pixels = Int((pointSize * 2).rounded())
        let fallback = NSImage(size: NSSize(width: pointSize, height: pointSize))
        let colorSpace = CGColorSpaceCreateDeviceRGB()
        guard let context = CGContext(
            data: nil,
            width: pixels,
            height: pixels,
            bitsPerComponent: 8,
            bytesPerRow: 0,
            space: colorSpace,
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
        ) else {{ return fallback }}

        // CG bitmap contexts have y pointing up while SVG paths have y pointing down; flip before drawing
        context.translateBy(x: 0, y: CGFloat(pixels))
        context.scaleBy(x: 1, y: -1)
        // 24×24 design space -> pixel size
        var transform = CGAffineTransform(scaleX: CGFloat(pixels) / 24, y: CGFloat(pixels) / 24)
        context.setFillColor(CGColor(gray: 0, alpha: 1))

        // Fill the two stars separately: in the SVG they are two independent
        // path elements, each filled with nonzero; when merged into one path
        // the two subpaths wind in opposite directions, the winding numbers
        // cancel to 0 where they overlap, and a cross-shaped hole is punched
        // in the middle of the front star (measured).
        for path in [MenuBarStarPath.back, MenuBarStarPath.front] {{
            context.addPath(path.copy(using: &transform) ?? path)
            context.fillPath()
        }}

        guard let cgImage = context.makeImage() else {{ return fallback }}
        let image = NSImage(cgImage: cgImage, size: NSSize(width: pointSize, height: pointSize))
        image.isTemplate = true
        return image
    }}
}}

/// The two paths of the double star, in a 24×24 design space, for MenuBarIcon
/// to rasterize. They do not change after being built, and Swift guarantees
/// lazy initialization happens only once (thread-safe), so they can be treated
/// as immutable globals; CGPath is not Sendable, hence the explicit exemption
/// under strict concurrency.
enum MenuBarStarPath {{
    /// Back star: the small four-pointed star + small cross, the one partly
    /// obscured by the front star in the original SVG.
    nonisolated(unsafe) static let back: CGPath = {{
        let path = CGMutablePath()
{back_body}
        return path
    }}()

    /// Front star: the large four-pointed star forming the frosted-glass body.
    nonisolated(unsafe) static let front: CGPath = {{
        let path = CGMutablePath()
{front_body}
        return path
    }}()
}}
'''


def main():
    svg = SVG.read_text()
    # Path order: 0=back star (origin) 1=back star clone (blur) 2=front star (blur) 3=highlight
    ds = re.findall(r'<path\s+d="([^"]+)"', svg)
    if len(ds) < 3:
        sys.exit(f"期望至少 3 个 path，实际 {len(ds)}")
    back, front = ds[0], ds[2]

    back_body = "\n".join(["        " + line for line in to_swift(tokenize(back))])
    front_body = "\n".join(["        " + line for line in to_swift(tokenize(front))])

    SWIFT_OUT.write_text(
        SWIFT_TEMPLATE.format(back_body=back_body, front_body=front_body)
    )
    MONO_OUT.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">'
        f'<path d="{back}" fill="#000"/><path d="{front}" fill="#000"/></svg>'
    )
    print(f"{SWIFT_OUT}")
    print(f"{MONO_OUT}")


if __name__ == "__main__":
    main()
